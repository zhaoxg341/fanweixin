package cn.itcast.weixin.utils;

import java.util.Random;

/**
 * 好友的「关键词自动回复」规则。
 *
 * 规则按数组顺序匹配，命中第一条就返回，所以**越具体的规则要放越前面**。
 * 比如「你好吗」必须排在「你好」前面，否则永远只会命中「你好」。
 *
 * 一条回复可以写多种说法，用竖线隔开，命中时随机挑一句，看起来不那么像机器人：
 *   {"你好", "你好|你好呀，很高兴认识你|嗨～"}
 *
 * 想加新规则，只要往 RULES 里加一行 {"触发词", "回复内容"} 即可，
 * 不用改 ChatActivity 的任何逻辑。匹配用的是 contains，
 * 所以「你今天吃饭了吗」也能命中「吃饭了吗」。没命中就返回 null，
 * 由调用方走原来那几句随机回复。
 */
public class AutoReplyRules {

    /** 同一句回复的多个候选，用 | 分隔 */
    private static final String SEPARATOR = "\\|";

    private static final Random RANDOM = new Random();

    /**
     * 注意顺序：长关键词 / 更具体的说法放前面。
     * 现在覆盖了打招呼、吃饭、道别、夸人、日常闲聊等常见话术。
     */
    private static final String[][] RULES = {
            // ---------- 吃饭 ----------
            {"吃饭了吗", "吃了|刚吃完，你呢|还没呢，你请客吗"},
            {"你吃了吗", "吃了，你呢|刚吃完"},
            {"吃了吗", "吃了|还没，等会儿去吃"},
            {"我饿了", "那快去吃饭呀|我也是，一起？"},

            // ---------- 恋爱 / 八卦 ----------
            {"你喜欢谁", "我是同性恋"},
            {"你喜欢我吗", "你猜呀|这个嘛…保密"},
            {"我爱你", "我…我也是|突然这么肉麻干嘛"},

            // ---------- 打招呼 ----------
            {"你好吗", "挺好的，你呢|还不错，就是有点忙"},
            {"你好", "你好|你好呀，很高兴认识你|嗨～"},
            {"嗨", "嗨～|在呢"},
            {"在吗", "在的，怎么啦|在，你说"},
            {"你在干嘛", "在摸鱼，哈哈|刚忙完，怎么啦"},
            {"在干嘛", "在摸鱼，哈哈|没干嘛，正想找你聊天"},
            {"忙吗", "有点忙，等我一下|不忙，你说"},
            {"在忙吗", "有点忙，稍等一下|还好，怎么了"},
            {"有空吗", "有呀，怎么了|现在有空"},

            // ---------- 问候 ----------
            {"早上好", "早上好呀|早，今天也要开心"},
            {"早安", "早安～|早呀"},
            {"中午好", "中午好，吃饭了吗"},
            {"下午好", "下午好呀"},
            {"晚上好", "晚上好～|晚上好，今天过得怎么样"},
            {"晚安", "晚安，好梦|晚安，早点睡"},

            // ---------- 道谢 / 道别 ----------
            {"谢谢", "不客气～|小事，别客气"},
            {"多谢", "不客气～"},
            {"再见", "拜拜，回头聊|好，下次见"},
            {"拜拜", "拜拜～|回头聊"},
            {"明天见", "明天见～"},

            // ---------- 日常闲聊 ----------
            {"生日快乐", "谢谢你还记得我的生日！|哇，谢谢你"},
            {"新年快乐", "新年快乐，万事顺意"},
            {"天气", "今天天气不错，适合出门|我这边有点热"},
            {"你叫什么", "你猜呀|叫我名字就好"},
            {"你是谁", "我是你的好朋友呀"},
            {"你几岁", "保密|你猜"},
            {"你是男的女的", "你猜呀"},
            {"你住哪", "就在你隔壁呀|不告诉你"},
            {"你厉害", "没有啦，你也很棒"},
            {"加油", "一起加油！"},
            {"无聊", "那聊点别的？|要不出去走走"},
            {"困了", "那早点睡吧|晚安，好梦"},
            {"我困了", "那快去睡，晚安"},
            {"好的", "好嘞|行，就这么说定了"},
            {"哈哈", "哈哈哈，你笑什么|笑得这么开心"},
            {"出来玩吗", "好呀，去哪|可以呀，什么时候"},
            {"周末愉快", "周末愉快！"}
    };

    private AutoReplyRules() {
    }

    /**
     * 根据我发出的内容决定回什么。
     *
     * @param input 我发送的原文
     * @return 命中的回复内容；没命中返回 null
     */
    public static String replyFor(String input) {
        if (input == null) {
            return null;
        }
        String text = input.trim();
        if (text.isEmpty()) {
            return null;
        }
        for (String[] rule : RULES) {
            // 用 contains 而不是 equals：这样"你今天吃饭了吗"也能命中
            if (text.contains(rule[0])) {
                return pick(rule[1]);
            }
        }
        return null;
    }

    /** 一条规则可能配了多个回复，随机挑一个 */
    private static String pick(String replies) {
        String[] choices = replies.split(SEPARATOR);
        if (choices.length == 1) {
            return choices[0];
        }
        return choices[RANDOM.nextInt(choices.length)];
    }
}
